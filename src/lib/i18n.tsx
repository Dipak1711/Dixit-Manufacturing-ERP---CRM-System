interface I18n { lang: Lang; setLang: (l: Lang) => void; t: (s: string) => string; }
const Ctx = createContext<I18n>({ lang: "en", setLang: () => {}, t: (s) => s });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try { return (localStorage.getItem("dx-lang") as Lang) || "en"; } catch { return "en"; }
  });
  useEffect(() => {
    try { localStorage.setItem("dx-lang", lang); } catch { /* storage unavailable */ }
    document.documentElement.lang = lang;
  }, [lang]);
  const value = useMemo<I18n>(
    () => ({ lang, setLang, t: (s) => (lang === "en" ? s : D[s]?.[lang] ?? s) }),
    [lang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}
export const useI18n = () => useContext(Ctx);
